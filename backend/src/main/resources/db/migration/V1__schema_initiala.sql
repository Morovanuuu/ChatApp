CREATE TABLE utilizator (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(150) NOT NULL UNIQUE,
    parola_hash VARCHAR(100) NOT NULL,
    nume        VARCHAR(100) NOT NULL,
    rol         VARCHAR(20)  NOT NULL CHECK (rol IN ('ADMIN', 'USER')),
    creat_la    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- nume NULL = conversatie privata intre doi utilizatori; altfel grup
CREATE TABLE conversatie (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume     VARCHAR(100),
    creat_la TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Tabela de legatura N-N: utilizator <-> conversatie
CREATE TABLE membru_conversatie (
    conversatie_id BIGINT    NOT NULL REFERENCES conversatie (id) ON DELETE CASCADE,
    utilizator_id  BIGINT    NOT NULL REFERENCES utilizator (id) ON DELETE CASCADE,
    intrat_la      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (conversatie_id, utilizator_id)
);

CREATE INDEX idx_membru_utilizator ON membru_conversatie (utilizator_id);

CREATE TABLE mesaj (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversatie_id BIGINT        NOT NULL REFERENCES conversatie (id) ON DELETE CASCADE,
    autor_id       BIGINT        NOT NULL REFERENCES utilizator (id),
    continut       VARCHAR(2000) NOT NULL,
    trimis_la      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Mesajele unei conversatii se citesc mereu in ordine cronologica
CREATE INDEX idx_mesaj_conversatie ON mesaj (conversatie_id, trimis_la);
